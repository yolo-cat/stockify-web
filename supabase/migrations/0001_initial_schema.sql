  dividend_income double precision not null default 0 check (dividend_income >= 0),
  supplementary_nhi_fee double precision not null default 0 check (supplementary_nhi_fee >= 0),
  stock_dividend double precision not null default 0 check (stock_dividend >= 0),
  dividend_shares double precision not null default 0 check (dividend_shares >= 0),
  ex_rights_shares double precision not null default 0 check (ex_rights_shares >= 0),
  note text not null default '',
  capital_reduction_ratio double precision not null default 0 check (capital_reduction_ratio >= 0 and capital_reduction_ratio < 100),
  shares_before_reduction double precision not null default 0 check (shares_before_reduction >= 0),
  shares_after_reduction double precision not null default 0 check (shares_after_reduction >= 0),
  cash_returned double precision not null default 0 check (cash_returned >= 0),
  stock_split_ratio double precision not null default 0 check (stock_split_ratio >= 0),
  shares_before_split double precision not null default 0 check (shares_before_split >= 0),
  shares_after_split double precision not null default 0 check (shares_after_split >= 0),
  margin_principal double precision not null default 0 check (margin_principal >= 0),
  margin_annual_rate double precision not null default 0 check (margin_annual_rate >= 0),
  margin_lot_id text not null default '',
  margin_repayment_lot_id text not null default '',
  margin_repayment double precision not null default 0 check (margin_repayment >= 0),
  margin_self_funded double precision not null default 0 check (margin_self_funded >= 0),
  margin_self_funded_overridden boolean not null default false,
  margin_actual_interest double precision not null default 0 check (margin_actual_interest >= 0),
  short_borrow_principal double precision not null default 0 check (short_borrow_principal >= 0),
  short_borrow_annual_rate double precision not null default 0 check (short_borrow_annual_rate >= 0),
  short_lot_id text not null default '',
  short_cover_lot_id text not null default '',
  short_cover_shares double precision not null default 0 check (short_cover_shares >= 0),
  short_compensation_lot_id text not null default '',
  short_compensation double precision not null default 0 check (short_compensation >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_transactions_stock_order
  on public.transactions (user_id, market, stock_code, date, record_time, id);

create index if not exists idx_transactions_date_order
  on public.transactions (user_id, date, record_time, id);

create index if not exists idx_transactions_stock_account
