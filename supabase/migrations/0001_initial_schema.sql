-- Stockify Web v1 Initial Schema (Lovable Cloud / Supabase PostgreSQL)
-- Matches docs/android-to-web-spec.md with strict RLS on all user-owned and shared tables.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- =============================================================================
-- 1. User-owned: accounts
-- =============================================================================
create table if not exists public.accounts (
  user_id uuid not null references auth.users(id) on delete cascade,
  id integer not null check (id > 0),
  name text not null check (length(btrim(name)) > 0),
  fee_discount double precision check (fee_discount is null or fee_discount >= 0),
  min_fee_regular integer check (min_fee_regular is null or min_fee_regular >= 0),
  min_fee_odd_lot integer check (min_fee_odd_lot is null or min_fee_odd_lot >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

create trigger trg_accounts_updated_at
  before update on public.accounts
  for each row execute function public.set_updated_at();

alter table public.accounts enable row level security;

create policy "accounts_select_own"
  on public.accounts for select
  to authenticated
  using (auth.uid() = user_id);

create policy "accounts_insert_own"
  on public.accounts for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "accounts_update_own"
  on public.accounts for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "accounts_delete_own"
  on public.accounts for delete
  to authenticated
  using (auth.uid() = user_id);

